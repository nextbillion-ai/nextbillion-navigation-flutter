import CoreLocation
import Foundation
import NbmapCoreNavigation

/// Serializes platform objects, including fused offline reroutes whose `json`
/// is nil. Existing response fields are retained; navigation geometry/guidance
/// always comes from the current route, never from pre-reroute JSON.
enum NavigationRouteCodec {
    static func encode(_ route: Route) throws -> String {
        var root = route.json.map(Convert.jsonStringToDictionary) ?? [:]
        let originalLegs = root["legs"] as? [[String: Any]] ?? []
        let precision = route.routeOptions.shapeFormat == .polyline ? 1e5 : 1e6
        root["distance"] = route.distance
        root["duration"] = route.expectedTravelTime
        root["geometry"] = polyline(route.coordinates ?? [], precision: precision)
        root["voiceLocale"] = route.speechLocale?.identifier
        root["routeOptions"] = Convert.convertRouteOptionsToMap(routeOptions: route.routeOptions)
        // Guidance below is already generated by the SDK. Reprocessing it after
        // JSON reconstruction would shift predecessor-owned voice cues again.
        root["_nbFlutterGuidanceReady"] = true
        root["legs"] = route.legs.enumerated().map { index, leg in
            var json = index < originalLegs.count ? originalLegs[index] : [:]
            let steps = json["steps"] as? [[String: Any]] ?? []
            json["distance"] = ["value": leg.distance]
            json["duration"] = ["value": leg.expectedTravelTime]
            json["summary"] = leg.name
            json["steps"] = leg.steps.enumerated().map { offset, step in
                stepMap(step, original: offset < steps.count ? steps[offset] : [:], precision: precision)
            }
            var annotation = json["annotation"] as? [String: Any] ?? [:]
            annotation["distance"] = leg.segmentDistances
            annotation["duration"] = leg.expectedSegmentTravelTimes
            annotation["speed"] = leg.segmentSpeeds
            if !annotation.isEmpty { json["annotation"] = annotation }
            return json
        }
        if let roadInfo = route.roadInfo {
            var json = root["road_info"] as? [String: Any] ?? [:]
            json["max_speed"] = roadInfo.maxSpeed.map { ["offset": $0.offset, "length": $0.length, "value": $0.value] as [String: Any] }
            json["truck_route"] = roadInfo.truckRoute.map { ["offset": $0.offset, "length": $0.length, "value": $0.value] as [String: Any] }
            root["road_info"] = json
        }
        let data = try JSONSerialization.data(withJSONObject: root)
        return String(decoding: data, as: UTF8.self)
    }

    private static func stepMap(_ step: RouteStep, original: [String: Any], precision: Double) -> [String: Any] {
        var json = original
        json["distance"] = ["value": step.distance]
        json["duration"] = ["value": step.expectedTravelTime]
        let roundabout = step.maneuverType == .takeRoundabout || step.maneuverType == .takeRotary
        json["name"] = (roundabout ? step.exitNames : step.names)?.joined(separator: "; ") ?? ""
        json["rotary_name"] = roundabout ? step.names?.joined(separator: "; ") : nil
        json["pronunciation"] = (roundabout ? step.phoneticExitNames : step.phoneticNames)?.joined(separator: ";")
        json["rotary_pronunciation"] = roundabout ? step.phoneticNames?.joined(separator: ";") : nil
        json["ref"] = step.codes?.joined(separator: ";")
        json["exits"] = step.exitCodes?.joined(separator: ";")
        let destinations = step.destinations?.joined(separator: ",") ?? ""
        if let codes = step.destinationCodes, !codes.isEmpty {
            json["destinations"] = codes.joined(separator: ",") + ": " + destinations
        } else {
            json["destinations"] = step.destinations == nil ? nil : destinations
        }
        json["mode"] = step.transportType.description
        json["driving_side"] = step.drivingSide.description
        json["geometry"] = polyline(step.coordinates ?? [], precision: precision)
        json["start_location"] = step.startLocation.map(coordinate)
        json["end_location"] = step.endLocation.map(coordinate)
        var maneuver = json["maneuver"] as? [String: Any] ?? [:]
        maneuver["maneuver_type"] = step.maneuverType.description
        maneuver["modifier"] = step.maneuverDirection.description
        maneuver["instruction"] = step.instructions
        maneuver["display_instruction"] = step.displayInstruction
        maneuver["coordinate"] = step.maneuverLocation.map(coordinate)
        maneuver["bearing_before"] = step.initialHeading
        maneuver["bearing_after"] = step.finalHeading
        maneuver["bearing"] = step.bearing
        maneuver["muted"] = step.muted
        maneuver["exit"] = step.exitIndex
        let spoken = step.instructionsSpokenAlongStep?.map { instruction -> [String: Any] in
            var result: [String: Any] = ["instruction": instruction.text, "distance_along_geometry": instruction.distanceAlongStep]
            result["ssmlAnnouncement"] = instruction.ssmlText
            result["unit"] = instruction.unit?.symbol
            return result
        }
        maneuver["voice_instruction"] = spoken
        json["maneuver"] = maneuver
        json["voiceInstructions"] = spoken
        json["bannerInstructions"] = step.instructionsDisplayedAlongStep?.map { banner -> [String: Any] in
            var result: [String: Any] = ["distanceAlongGeometry": banner.distanceAlongStep]
            result["primary"] = banner.primaryInstruction.map(instructionMap)
            result["secondary"] = banner.secondaryInstruction.map(instructionMap)
            result["sub"] = banner.tertiaryInstruction.map(instructionMap)
            return result
        }
        json["intersections"] = step.intersections?.map { intersection -> [String: Any] in
            var result: [String: Any] = ["bearings": intersection.headings,
                "entry": intersection.headings.indices.map { intersection.outletIndexes.contains($0) },
                "intersection_in": validIndex(intersection.approachIndex, count: intersection.headings.count),
                "intersection_out": validIndex(intersection.outletIndex, count: intersection.headings.count)]
            result["location"] = intersection.location.map(coordinate)
            result["classes"] = intersection.outletRoadClasses
            result["lanes"] = intersection.approachLanes?.enumerated().map { index, lane in
                ["indications": lane.indications.description.components(separatedBy: ","),
                 "valid": intersection.usableApproachLanes?.contains(index) ?? false] as [String: Any]
            }
            return result
        }
        if step.shiledImageUrl != nil || step.shiledLabel != nil {
            var shield: [String: Any] = [:]
            shield["image_url"] = step.shiledImageUrl?.absoluteString
            shield["label"] = step.shiledLabel
            json["road_shield_type"] = shield
        }
        return json
    }

    private static func instructionMap(_ instruction: VisualInstruction) -> [String: Any] {
        var json: [String: Any] = ["type": instruction.maneuverType.description,
            "modifier": instruction.maneuverDirection.description]
        if instruction.hasKnownRoundaboutAngle { json["degrees"] = instruction.finalHeading }
        json["text"] = instruction.text
        json["instruction"] = instruction.instruction
        json["components"] = instruction.components.map { component -> [String: Any] in
            if let lane = component as? LaneIndicationComponent {
                return ["type": "lane", "directions": lane.indications.description.components(separatedBy: ","), "active": lane.isUsable]
            }
            guard let component = component as? VisualInstructionComponent else { return [:] }
            var result: [String: Any] = ["type": component.type.description, "abbr_priority": component.abbreviationPriority]
            result["text"] = component.text
            result["imageURL"] = component.imageURL?.absoluteString
            result["label"] = component.label
            result["abbr"] = component.abbreviation
            return result
        }
        return json
    }

    private static func validIndex(_ index: Int, count: Int) -> Int {
        (0..<count).contains(index) ? index : -1
    }

    /// The SDK's JSON initializer only accepts imageBaseURL. Restore resolved
    /// URLs explicitly rather than guessing a base URL or appending scale twice.
    static func restoreComponentResources(in route: Route, from root: [String: Any]) {
        let legs = root["legs"] as? [[String: Any]] ?? []
        for (leg, json) in zip(route.legs, legs) {
            let steps = json["steps"] as? [[String: Any]] ?? []
            for (step, json) in zip(leg.steps, steps) {
                let banners = json["bannerInstructions"] as? [[String: Any]] ?? []
                for (banner, json) in zip(step.instructionsDisplayedAlongStep ?? [], banners) {
                    for (instruction, key) in [(banner.primaryInstruction, "primary"),
                                               (banner.secondaryInstruction, "secondary"),
                                               (banner.tertiaryInstruction, "sub")] {
                        guard let instruction,
                              let value = json[key] as? [String: Any],
                              let components = value["components"] as? [[String: Any]] else { continue }
                        for (component, json) in zip(instruction.components, components) {
                            guard let component = component as? VisualInstructionComponent else { continue }
                            if let url = (json["imageURL"] ?? json["image_url"]) as? String {
                                component.imageURL = URL(string: url)
                            }
                        }
                    }
                }
            }
        }
    }

    private static func coordinate(_ value: CLLocationCoordinate2D) -> [String: Double] {
        ["latitude": value.latitude, "longitude": value.longitude]
    }

    private static func polyline(_ coordinates: [CLLocationCoordinate2D], precision: Double) -> String {
        var result = [UInt8]()
        var latitude: Int64 = 0
        var longitude: Int64 = 0
        func append(_ delta: Int64) {
            var value = delta < 0 ? ~(delta << 1) : delta << 1
            while value >= 0x20 {
                result.append(UInt8((0x20 | (value & 0x1f)) + 63))
                value >>= 5
            }
            result.append(UInt8(value + 63))
        }
        for coordinate in coordinates {
            let nextLat = Int64((coordinate.latitude * precision).rounded())
            let nextLon = Int64((coordinate.longitude * precision).rounded())
            append(nextLat - latitude); append(nextLon - longitude)
            latitude = nextLat; longitude = nextLon
        }
        return String(decoding: result, as: UTF8.self)
    }
}
